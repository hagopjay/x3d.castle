#!/usr/bin/env python3
"""Markdown tables and paired statistics from a run_quality.py results.json (no renders, no network).

    python3 tools/quality_tables.py results/quality/public/results.json > docs/quality-tables.md

Needs numpy, Pillow, scipy and flip-evaluator (the venv run_quality.py already uses) for the footprint split; pass
--no-footprint to skip it (then only results.json is read).

Every number printed here is a function of results.json and the leg PNGs next to it. Nothing is tuned.
Definitions (the same words as in docs/quality-leg.md):
  F          flip_mean: mean FLIP (LDR, 67 ppd, flip-evaluator 1.7) of the leg against the Cycles reference, whole frame. Lower is better.
  E          flip_mean_expnorm: F after one linear-light exposure scalar that matches the mean luminance of the non-background pixels
             to the reference. Secondary: its mask is built per pair, so it is not comparable across legs when the sky differs,
             and it can hide a wrong brightness (exposure scale far from 1).
  footprint  reference non-background pixels plus a 3 px halo, "in" and "out" are the two parts of F (they add up to F).
  core 11    the 15 scenes minus the four whose reference is structurally not the X3D file (the add-on drops NurbsCurve and
             GaussianSplats, flattens the gradient Background, or ignores the attenuation field): annotation-standard,
             nurbs-weights, quaternion-xyzw, p2-point-classic.
  bootstrap  paired resampling of scenes (5000, seed 1). Scenes are not independent (p1..p5 are one probe design), so the
             intervals are indicative.
"""
import argparse, json, os, sys
import numpy as np

CORE_LEGS = ['xite', 'babylon_addon', 'babylon_castle', 'castle_native', 'castle_all']
EXCLUDED = ['annotation-standard', 'nurbs-weights', 'quaternion-xyzw', 'p2-point-classic']


def load(path):
    return json.load(open(path))


def val(scenes, s, leg, key='flip_mean', vs='vs_ref'):
    try:
        return scenes[s]['legs'][leg][vs][key]
    except (KeyError, TypeError):
        return None


def fmt(x, n=4):
    return '-' if x is None else ('%.*f' % (n, x))


def boot(a, b, n=5000, seed=1):
    """paired scene bootstrap of mean(a-b): (mean, lo, hi, wins_a, wins_b)"""
    d = np.array(a) - np.array(b)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(d), size=(n, len(d)))
    m = d[idx].mean(axis=1)
    return d.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5), int((d < 0).sum()), int((d > 0).sum())


def footprint(results_dir, scenes, legs):
    import flip_evaluator
    from PIL import Image
    from scipy import ndimage as ndi
    out = {}
    for s in scenes:
        ref = np.array(Image.open(os.path.join(results_dir, s, 'ref.png')).convert('RGB'))
        corners = [tuple(ref[0, 0]), tuple(ref[0, -1]), tuple(ref[-1, 0]), tuple(ref[-1, -1])]
        bg = max(set(corners), key=corners.count)
        obj = ndi.binary_dilation(np.any(ref != np.array(bg), axis=2), iterations=3)
        out[s] = {'frac': float(obj.mean())}
        for l in legs:
            p = os.path.join(results_dir, s, l + '.png')
            if not os.path.exists(p):
                continue
            t = np.array(Image.open(p).convert('RGB'))
            err, _, _ = flip_evaluator.evaluate(np.ascontiguousarray(ref / 255.0, dtype=np.float32),
                                                np.ascontiguousarray(t / 255.0, dtype=np.float32), 'LDR',
                                                inputsRGB=True, applyMagma=False, computeMeanError=True)
            err = np.asarray(err)
            if err.ndim == 3:
                err = err[..., 0]
            out[s][l] = (float((err * obj).sum() / err.size), float((err * ~obj).sum() / err.size))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('results_json')
    ap.add_argument('--no-footprint', action='store_true')
    a = ap.parse_args()
    d = load(a.results_json)
    rd = os.path.dirname(os.path.abspath(a.results_json))
    sc = d['scenes']
    names = list(sc.keys())
    core11 = [s for s in names if s not in EXCLUDED]
    md = d['metadata']
    print('# Quality tables (generated by tools/quality_tables.py)\n')
    print('Source: `results.json` from run_quality.py (%s, %s). Reference: %s %s CPU, %s spp, add-on %s. '
          'Metric: FLIP LDR, flip-evaluator 1.7.\n' % (md.get('tool'), md.get('date_utc'),
          md['reference']['renderer'].split(' (')[0], md['reference']['blender']['version'],
          md['reference']['samples'], md['reference']['addon_commit'][:7]))

    def table(title, key, legs, rows, note=''):
        print('## %s\n' % title)
        if note:
            print(note + '\n')
        print('| scene | ' + ' | '.join(legs) + ' |')
        print('|---|' + '---:|' * len(legs))
        for s in rows:
            print('| %s | %s |' % (s, ' | '.join(fmt(val(sc, s, l, key)) for l in legs)))
        for label, ss in (('mean, all %d' % len(names), names), ('mean, core %d' % len(core11), core11)):
            cells = []
            for l in legs:
                v = [val(sc, s, l, key) for s in ss]
                cells.append(fmt(float(np.mean(v))) if all(x is not None for x in v) else '-')
            print('| **%s** | %s |' % (label, ' | '.join(cells)))
        v = [val(sc, s, l, key) for l in legs for s in names]
        print()

    legs = CORE_LEGS
    nf = {s: sc[s]['noise_floor']['flip_mean'] for s in names}
    print('## Seed-to-seed spread of the reference\n')
    print('Cycles seed 0 against seed 1, FLIP: mean %.4f, max %.4f over %d scenes. Reseeding the reference moves any leg\'s F by '
          'far less than this (a skeptic re-scored every leg against seed 1 and a 512 spp average: changes of at most 0.00014 per '
          'leg and the leg order did not change in any scene), so it is the spread of the reference image itself, '
          'not the error bar of a leg-against-leg comparison.\n' % (np.mean(list(nf.values())), max(nf.values()), len(nf)))
    table('F (flip_mean) against the Cycles reference, whole frame', 'flip_mean', legs, names)
    table('E (flip_mean_expnorm), secondary', 'flip_mean_expnorm', legs, names,
          'Read with the caveats in the module docstring: the mask is per pair, the sky scenes differ between legs, and an '
          'exposure scale far from 1 is hidden by E.')

    print('## Exposure scale (the factor that matches the leg to the reference; below 1 means the leg is too bright)\n')
    print('| scene | ' + ' | '.join(legs) + ' |')
    print('|---|' + '---:|' * len(legs))
    for s in names:
        print('| %s | %s |' % (s, ' | '.join(fmt(val(sc, s, l, 'exposure_scale'), 3) for l in legs)))
    print()

    print('## Paired scene bootstrap of F differences (negative: first leg is closer to the reference)\n')
    print('| pair | scenes | mean diff | 95% interval | scenes won / lost |')
    print('|---|---|---:|---|---|')
    for x, y in (('babylon_addon', 'xite'), ('babylon_castle', 'xite'), ('castle_native', 'xite'),
                 ('castle_native', 'babylon_castle'), ('castle_all', 'castle_native')):
        for label, ss in (('all %d' % len(names), names), ('core %d' % len(core11), core11)):
            av = [val(sc, s, x) for s in ss]
            bv = [val(sc, s, y) for s in ss]
            if any(v is None for v in av + bv):
                continue
            m, lo, hi, w, l_ = boot(av, bv)
            print('| %s - %s | %s | %+.4f | [%+.4f, %+.4f] | %d / %d |' % (x, y, label, m, lo, hi, w, l_))
    print()

    levers = sorted({l for s in names for l in sc[s]['legs'] if l.startswith('castle_') and l not in ('castle_native', 'castle_all', 'castle_input')})
    print('## Castle levers, one at a time (F change against castle_native, same scene, same reference)\n')
    print('Negative = closer to the reference. "better / worse" counts scenes with a change below -0.001 / above +0.001. '
          '"-" in a shadow column: shadow maps need a DirectionalLight or SpotLight, castle-render exits without a picture otherwise.\n')
    print('| lever | scenes | mean F change vs ref | core 11 | better / worse | vs ref_shadows (every light casts) |')
    print('|---|---:|---:|---:|---|---:|')
    for l in levers + ['castle_all']:
        ds, dc, dsh = [], [], []
        for s in names:
            a_, n_ = val(sc, s, l), val(sc, s, 'castle_native')
            if a_ is None or n_ is None:
                continue
            ds.append(a_ - n_)
            if s in core11:
                dc.append(a_ - n_)
            a2, n2 = val(sc, s, l, vs='vs_ref_shadows'), val(sc, s, 'castle_native', vs='vs_ref_shadows')
            if a2 is not None and n2 is not None:
                dsh.append(a2 - n2)
        if not ds:
            continue
        print('| %s | %d | %+.4f | %s | %d / %d | %s |' % (l.replace('castle_', ''), len(ds), np.mean(ds),
              ('%+.4f' % np.mean(dc)) if dc else '-', sum(x < -0.001 for x in ds), sum(x > 0.001 for x in ds),
              ('%+.4f (n=%d)' % (np.mean(dsh), len(dsh))) if dsh else '-'))
    print()

    if not a.no_footprint:
        try:
            fp = footprint(rd, names, CORE_LEGS[:4])
        except Exception as e:  # missing scipy / flip-evaluator / PNGs
            print('(footprint split skipped: %s)\n' % e)
            fp = None
        if fp:
            print('## F split by the reference footprint\n')
            print('F = in + out. "in" is the error on the reference\'s object pixels (3 px halo), "out" the error on the rest of the frame '
                  '(sky, ground, anything the reference does not draw). A leg that draws the file\'s gradient Background is charged '
                  'for it in "out" because the reference clears to one flat colour.\n')
            print('| scene | footprint | ' + ' | '.join('%s in / out' % l for l in CORE_LEGS[:4]) + ' |')
            print('|---|---:|' + '---|' * 4)
            for s in names:
                cells = []
                for l in CORE_LEGS[:4]:
                    t = fp[s].get(l)
                    cells.append('-' if t is None else '%.4f / %.4f' % t)
                print('| %s | %.2f | %s |' % (s, fp[s]['frac'], ' | '.join(cells)))
            tot = {l: [np.mean([fp[s][l][i] for s in names]) for i in (0, 1)] for l in CORE_LEGS[:4]}
            print('| **mean, all %d** | | %s |' % (len(names), ' | '.join('%.4f / %.4f' % tuple(tot[l]) for l in CORE_LEGS[:4])))
            print()


if __name__ == '__main__':
    main()
